# Function generating a Pseudo-random Noise (PN) code for DSSS. A simple implementation using Linear Feedback Shift Register (LFSR).
# Since we are hiding the signal for the receiver, we can use a simple PN code. 

# Gold code generator for DSSS spreading. This is a simple implementation and can be replaced with more complex codes if needed.
# ====== Gold code function has been generated by LLM ======
function generate_gold_code(n_bits::Int)
    # Standard 7-bit LFSR preferred pairs for a length-127 sequence
    # Polynomials: x^7 + x^3 + 1 and x^7 + x^3 + x^2 + x^1 + 1
    reg1 = ones(Int, 7)
    reg2 = ones(Int, 7)
    
    code = zeros(Float64, n_bits)
    
    for i in 1:n_bits
        # XOR the outputs of the two registers
        code[i] = (reg1[end] != reg2[end]) ? 1.0 : -1.0
        
        # Shift Register 1 Feedback
        fb1 = xor(reg1[7], reg1[3])
        reg1 = vcat(fb1, reg1[1:6])
        
        # Shift Register 2 Feedback
        fb2 = xor(xor(xor(reg2[7], reg2[3]), reg2[2]), reg2[1])
        reg2 = vcat(fb2, reg2[1:6])
    end
    return code
end

# Apply DSSS spreading to QPSK symbols and return "chips"
function apply_dsss(I_syms, Q_syms, PN_code, num_symbols)
    spread_I = Float64[]
    spread_Q = Float64[]

    for i in 1:num_symbols
        append!(spread_I, I_syms[i] .* PN_code)
        append!(spread_Q, Q_syms[i] .* PN_code)
    end
    return spread_I, spread_Q
end

# Apply Frequency Hopping Spread Spectrum (the final stealth layer). This function applies 
# frequency hopping by modulating the shaped I and Q signals with a hopping carrier with randomly
# or deterministically defined frequencies
function apply_frequency_hopping(I_shaped, Q_shaped, fs, hop_rate, hop_freq)
    N = length(I_shaped)
    t = 0:N-1 ./ fs

    # samples per hop
    sph = floor(Int, fs / hop_rate)
    num_hops = ceil(Int, N / sph)

    # Create the hop carrier
    phase = 0.0
    carrier = zeros(ComplexF64, N)

    for hop in 0:num_hops-1
        # Determine the frequency for this hop. Either random or deterministic
        f_hop = hop_freq[hop % length(hop_freq) + 1] # Cycle through hop frequencies

        # Indices for this hop
        idx_start = hop * sph + 1
        idx_end = min((hop + 1) * sph, N)
        # Vectorising for readability
        carrier[idx_start:idx_end] = exp.(im * (2π * f_hop / fs .* (1:length(idx_start:idx_end))))
    end

    # Up-convert the I and Q shaped signals with the hop carrier
    baseband = I_shaped .+ im .* Q_shaped
    hopped_signal = real.(baseband .* carrier)
    return hopped_signal
end

