""" sps: samples per symbol or chips
    N: total number of samples
    num_symbols: number of symbols to generate
    β: roll-off factor for RRC filter
    span: span of the RRC filter in symbol durations
"""


# Generating BPSK signal
function generate_bpsk_signal(num_symbols, sps, N)

    bits = rand(0:1, num_symbols)  # Random bits
    symbols = 2 .* bits .- 1.0  # Map bits to BPSK symbols (-1, +1)

    baseband = repeat(symbols, inner=sps)  # Baseband signal, "Rectangular pulse". Will be updated to "Raised Cosine" later.

    # Ensure baseband length matches N
    bb_length = length(baseband)
    bb_length < N ? baseband = baseband[1:N] : bb_length > N ? append!(baseband, zeros(bb_length - N)) : nothing

    # Passband signal
    # s(t) = I(t) * cos(2πf_ct) - Q(t) * sin(2πf_ct), where for BPSK, Q(t) = 0
    carrier_wave = cos.(2π * fc .* t)
    bpsk_signal_clean = baseband .* carrier_wave

    # Additive White Gaussian Noise (AWGN)
    SNR_dB = 10.0  # Signal to noise ratio in db
    signal_power = mean(abs2, bpsk_signal_clean)
    noise_power = signal_power / (10^(SNR_dB / 10))
    noise = sqrt(noise_power) * randn(Int(N))
    signal_received = bpsk_signal_clean + noise
    return signal_received, baseband, bpsk_signal_clean
end

# Generating QPSK symbols
function generate_qpsk_symbols(num_symbols)

    bits = rand(0:1, 2 * num_symbols) # Random bits
    # Reshape bits into a 2-row matrix to process pairs
    bit_pairs = reshape(bits, 2, :)

    # Map bit pairs to QPSK symbols
    # Map 0 -> -1 and 1 -> +1
    I_syms = 2 .* bit_pairs[1, :] .- 1.0
    Q_syms = 2 .* bit_pairs[2, :] .- 1.0
    return I_syms, Q_syms
end

# Create an RRC filter that will be applied to the spread signal to shape the pulses and limit bandwidth. This is also the matched filter at the receiver.
function apply_rrc_impulse_response(sps, β, span)
    T = 1.0 # normalised symbol period
    Ts = T / sps  # Sampling period
    t = collect(-span*T/2:Ts:span*T/2)  # Time vector for impulse response
    
    h = zeros(length(t))
    
    for i in eachindex(t) # Compute the RRC impulse response from the mathematical definition
        t_i = t[i]
        if t_i == 0
            h[i] = 1.0 + β * (4 / π - 1)
        elseif abs(t_i) == T / (4β)
            h[i] = (β / sqrt(2)) * ((1 + 2 / π) * sin(π / (4β)) + (1 - 2 / π) * cos(π / (4β)))
        else
            num = sin(π * t_i / T * (1 - β)) + 4 * β * t_i / T * cos(π * t_i / T * (1 + β))
            denom = π * t_i / T * (1 - (4 * β * t_i / T)^2)
            h[i] = num / denom
        end
    end
    # Normalise the filter coefficients
    h_rrc = h ./ sqrt(sum(h.^2))
    return h_rrc
end

