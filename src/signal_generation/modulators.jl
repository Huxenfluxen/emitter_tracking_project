# 4. FREQUENCY HOPPING & CHANNEL
# ==============================================================================
# Apply Frequency Hopping Spread Spectrum (the final stealth layer). This function applies 
# frequency hopping by modulating the shaped I and Q signals with a hopping carrier with randomly
# or deterministically defined frequencies
function apply_frequency_hopping(baseband_signal::Vector{ComplexF64}, fs::Float64, hop_rate::Float64, hop_freq::Vector{Float64})
    N = length(baseband_signal)
    t = 0:N-1 ./ fs

    # samples per hop
    sph = floor(Int, fs / hop_rate)
    num_hops = ceil(Int, N / sph)

    # Create the hop carrier
    phase = 0.0
    carrier = zeros(ComplexF64, N)

    for hop in 0:num_hops-1
        # Determine the frequency for this hop. Either random or deterministic
        f_hop = hop_freq[hop % length(hop_freq) + 1] # Cycle through hop frequencies

        # Indices for this hop
        idx_start = hop * sph + 1
        idx_end = min((hop + 1) * sph, N)
        # Vectorising for readability
        carrier[idx_start:idx_end] = exp.(im * (2π * f_hop / fs .* (1:length(idx_start:idx_end))))
    end

    # Up-convert the I and Q shaped signals with the hop carrier
    hopped_passband_signal = real.(baseband_signal .* carrier)
    return hopped_passband_signal
end

# Rayleigh fading function
# This will be updated to include Doppler effects and frequency selective fading in the future.
function apply_rayleigh_fading(signal; doppler=false)
    N = length(signal)
    # We draw Gaussian random variables to create the fading coefficients. In practice, these would be based on the physical environment and mobility.
    # Simple variant of Rayleigh fading with Doppler effect. In practice, this would be more complex and 
    # depend on the velocity of the transmitter/receiver and the carrier frequency.
    # This Doppler effect is actually called Fast Rayleigh Fading, while the velocity dependency can be a "Jakes Model" or similar. 
    
    fading_coefficients = doppler ? randn(N) + im * randn(N) : randn() + im * randn() # Single fading for flat fading, or a vector for frequency selective fading
    channel_gain = fading_coefficients ./ sqrt(mean(abs2, fading_coefficients)) # Normalise the fading

    signal_faded = signal .* channel_gain
    return signal_faded, channel_gain
end

# Additive White Gaussian Noise (AWGN) function
function apply_awgn(signal; SNR_dB=-5.0)
    signal_power = mean(abs2, signal)
    noise_power = signal_power / (10^(SNR_dB / 10))
    noise = sqrt(noise_power / 2) .* randn(length(signal)) .+ im .* sqrt(noise_power / 2) .* randn(length(signal))
    signal_final = signal .+ noise
    return signal_final
end

function apply_channel_effects(signal::Vector{<:Number}, snr_db::Float64; doppler::Bool=false)
    signal_faded, channel_gain = apply_rayleigh_fading(signal, doppler=doppler)
    signal_final = apply_awgn(signal_faded, SNR_dB=snr_db)
    return signal_final, channel_gain
end

# ==============================================================================
# 5. RECEIVER UTILITIES (For plotting and verification)
# ==============================================================================
function demodulate_signal(signal::Vector{ComplexF64}, sps::Int, fc::Float64, fs::Float64, h_rrc::Vector{Float64})
    N = length(signal)
    t = (0:N-1) / fs
    carrier_I = cos.(2π * fc .* t)
    carrier_Q = sin.(2π * fc .* t)
    # Mixing part: multiply received signal with carriers to get I and Q components (bring it to baseband)
    # restore the amplitude by multiplying with 2
    I_demod = 2.0 .*signal .* carrier_I
    Q_demod = -2.0 .*signal .* carrier_Q

    # Trimming the tail to match length of original signal before convolution to avoid issues with the convolution and time vector lengths.
    # Find the delay created by the convolution with the RRC and trim the demodulated signals. 
    h_len = length(h_rrc)
    delay = floor(Int, h_len / 2)
    # Filtering part: Apply the matched filter (RRC) to the demodulated I and Q components, including the delay from convoluting.
    conv_indices = delay + 1 : delay + N
    I_filtered = conv(I_demod, h_rrc)[conv_indices]
    Q_filtered = conv(Q_demod, h_rrc)[conv_indices]

    sps_int = round(Int, sps) # Ensure sps is integer
    # Timing Recovery: Pick the correct sample (peak of the poulse) to decide the symbol
    # This is a simple timing offset. In practice, this would be determined by a timing recovery algorithm.
    # Thanks to the trimming, we can pick samples starting at idx 1 now.

    # filter_delay = Int(floor(length(h_rrc) / 2))
    # symbol_offset = Int(floor(sps_int / 2))
    # start_idx = filter_delay + symbol_offset

    start_idx = 1 # Start at the first sample after trimming. 
    indices = start_idx:sps_int:length(I_filtered) 
    
    I_scatter = I_filtered[indices]
    Q_scatter = Q_filtered[indices]

    return I_scatter, Q_scatter
end

# ==============================================================================
# 6. THE MASTER GENERATOR
# ==============================================================================
function generate_signal(emitter::TargetEmitter, num_symbols::Int)
    # 1. Baseband & Spreading
    syms = generate_qpsk_symbols(num_symbols)
    carrier_qpsk_signal = real.(syms) # For plotting the clean QPSK signal before spreading and hopping
    h_rrc = create_rrc_filter(emitter.sps, emitter.β, emitter.span)
    qpsk_passband_signal = apply_pulse_shaping(syms, h_rrc, emitter.sps) # This is the clean QPSK signal after pulse shaping, before spreading and hopping. We can use this for comparison in the plots.

    code = generate_gold_code(emitter.lfsr_bits)
    spread = apply_dsss(syms, code)
    
    h_rrc = create_rrc_filter(emitter.sps, emitter.β, emitter.span)
    dsss_baseband = apply_pulse_shaping(spread, h_rrc, emitter.sps)
    
    # 2. Upconvert & Hopping
    fhss_passband = apply_frequency_hopping(dsss_baseband, emitter.fs, emitter.hop_rate, emitter.hop_freq)
    
    # 3. Channel Effects
    final_rx, _ = apply_channel_effects(fhss_passband, emitter.snr_db; doppler=true)
    
    # Return everything neatly packaged!
    return (
        syms = syms,
        qpsk_clean = qpsk_passband_signal, 
        dsss = dsss_baseband,
        fhss = fhss_passband,
        final = final_rx,
        matched_filter = h_rrc
    )
end

