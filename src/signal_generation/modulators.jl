# ==============================================================================
# 2. MODULATION & SPREADING
# ==============================================================================
function generate_qpsk_symbols(num_symbols::Int)
    bits = rand(0:1, 2 * num_symbols) # Random bits
    # Reshape bits into a 2-row matrix to process pairs
    bit_pairs = reshape(bits, 2, :)

    # Map bit pairs to QPSK symbols
    # Map 0 -> -1 and 1 -> +1
    I_syms = 2 .* bit_pairs[1, :] .- 1.0
    Q_syms = 2 .* bit_pairs[2, :] .- 1.0
    # return I_syms, Q_syms
    # Combine them into a single complex array:
    complex_syms = I_syms .+ im .* Q_syms
    return complex_syms
end

# Function generating a Pseudo-random Noise (PN) code for DSSS. A simple implementation using Linear Feedback Shift Register (LFSR).
# Since we are hiding the signal for the receiver, we can use a simple PN code. 

# Gold code generator for DSSS spreading. This is a simple implementation and can be replaced with more complex codes if needed.
# ====== Gold code function has been generated by LLM ======
function generate_gold_code(n_bits::Int)
    # Standard 7-bit LFSR preferred pairs for a length-127 sequence
    # Polynomials: x^7 + x^3 + 1 and x^7 + x^3 + x^2 + x^1 + 1
    reg1 = ones(Int, 7)
    reg2 = ones(Int, 7)
    
    code = zeros(Float64, n_bits)
    
    for i in 1:n_bits
        # XOR the outputs of the two registers
        code[i] = (reg1[end] != reg2[end]) ? 1.0 : -1.0
        
        # Shift Register 1 Feedback
        fb1 = xor(reg1[7], reg1[3])
        reg1 = vcat(fb1, reg1[1:6])
        
        # Shift Register 2 Feedback
        fb2 = xor(xor(xor(reg2[7], reg2[3]), reg2[2]), reg2[1])
        reg2 = vcat(fb2, reg2[1:6])
    end
    return code
end

# Apply DSSS spreading to QPSK symbols
function apply_dsss(complex_syms::Vector{ComplexF64}, PN_code::Vector{Float64})
    # Kronecker product to spread the complex symbols
    spread_signal = kron(complex_syms, PN_code)
    return spread_signal ./ sqrt(length(PN_code)) # Normalise the power after spreading
end

# ==============================================================================
# 3. PULSE SHAPING
# ==============================================================================
# Create an RRC filter that will be applied to the spread signal to shape the pulses and limit bandwidth. This is also the matched filter at the receiver.
function create_rrc_filter(sps::Int, β::Float64, span::Int)
    T = 1.0 # normalised symbol period
    Ts = T / sps  # Sampling period
    t = collect(-span*T/2:Ts:span*T/2)  # Time vector for impulse response
    
    h = zeros(length(t))
    
    for i in eachindex(t) # Compute the RRC impulse response from the mathematical definition
        t_i = t[i]
        if t_i == 0
            h[i] = 1.0 + β * (4 / π - 1)
        elseif abs(t_i) == T / (4β)
            h[i] = (β / sqrt(2)) * ((1 + 2 / π) * sin(π / (4β)) + (1 - 2 / π) * cos(π / (4β)))
        else
            num = sin(π * t_i / T * (1 - β)) + 4 * β * t_i / T * cos(π * t_i / T * (1 + β))
            denom = π * t_i / T * (1 - (4 * β * t_i / T)^2)
            h[i] = num / denom
        end
    end
    # Normalise the filter coefficients
    h_rrc = h ./ sqrt(sum(h.^2))
    return h_rrc
end

function apply_pulse_shaping(spread_signal::Vector{ComplexF64}, h_rrc::Vector{Float64}, sps::Int)
    # Your exact code, adapted for complex numbers
    impulse_train = zeros(ComplexF64, length(spread_signal) * sps)
    impulse_train[1:sps:end] = spread_signal
    
    delay = floor(Int, length(h_rrc) / 2)
    conv_indices = delay + 1 : delay + length(impulse_train)
    
    # DSP.conv works on complex numbers natively!
    shaped_signal = conv(impulse_train, h_rrc)[conv_indices]
    
    return shaped_signal
end

