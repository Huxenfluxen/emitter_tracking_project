# 3. PULSE SHAPING
# ==============================================================================
# Create an RRC filter that will be applied to the spread signal to shape the pulses and limit bandwidth. This is also the matched filter at the receiver.
function create_rrc_filter(sps::Int, β::Float64, span::Int)
    T = 1.0 # normalised symbol period
    Ts = T / sps  # Sampling period
    t = collect(-span*T/2:Ts:span*T/2)  # Time vector for impulse response
    
    h = zeros(length(t))
    
    for i in eachindex(t) # Compute the RRC impulse response from the mathematical definition
        t_i = t[i]
        if t_i == 0
            h[i] = 1.0 + β * (4 / π - 1)
        elseif abs(t_i) == T / (4β)
            h[i] = (β / sqrt(2)) * ((1 + 2 / π) * sin(π / (4β)) + (1 - 2 / π) * cos(π / (4β)))
        else
            num = sin(π * t_i / T * (1 - β)) + 4 * β * t_i / T * cos(π * t_i / T * (1 + β))
            denom = π * t_i / T * (1 - (4 * β * t_i / T)^2)
            h[i] = num / denom
        end
    end
    # Normalise the filter coefficients
    h_rrc = h ./ sqrt(sum(h.^2))
    return h_rrc
end

function apply_pulse_shaping(spread_signal::Vector{ComplexF64}, h_rrc::Vector{Float64}, sps::Int)
    # Your exact code, adapted for complex numbers
    impulse_train = zeros(ComplexF64, length(spread_signal) * sps)
    impulse_train[1:sps:end] = spread_signal
    
    delay = floor(Int, length(h_rrc) / 2)
    conv_indices = delay + 1 : delay + length(impulse_train)
    
    shaped_signal = conv(impulse_train, h_rrc)[conv_indices]# .* sps # Scale by sps to maintain power level after convolution
    
    return shaped_signal
end

# ==============================================================================
# 4. FREQUENCY HOPPING & CHANNEL
# ==============================================================================
# Apply Frequency Hopping Spread Spectrum (the final stealth layer). This function applies 
# frequency hopping by modulating the shaped I and Q signals with a hopping carrier with randomly
# or deterministically defined frequencies
function apply_frequency_hopping(baseband_signal::Vector{ComplexF64}, fs::Float64, hop_rate::Float64, hop_freq::Vector{Float64})
    N = length(baseband_signal)
    t = 0:N-1 ./ fs

    # samples per hop
    sph = floor(Int, fs / hop_rate)
    num_hops = ceil(Int, N / sph)

    # Create the hop carrier
    phase = 0.0
    carrier = zeros(ComplexF64, N)

    for hop in 0:num_hops-1
        # Determine the frequency for this hop. Either random or deterministic
        f_hop = hop_freq[hop % length(hop_freq) + 1] # Cycle through hop frequencies

        # Indices for this hop
        idx_start = hop * sph + 1
        idx_end = min((hop + 1) * sph, N)
        # Vectorising for readability
        carrier[idx_start:idx_end] = exp.(im * (2π * f_hop / fs .* (1:length(idx_start:idx_end))))
    end

    # Up-convert the I and Q shaped signals with the hop carrier
    hopped_passband_signal = real.(baseband_signal .* carrier)
    return hopped_passband_signal
end

# Rayleigh fading function
# This will be updated to include Doppler effects and frequency selective fading in the future.
function apply_rayleigh_fading(signal; doppler=false)
    N = length(signal)
    # We draw Gaussian random variables to create the fading coefficients. In practice, these would be based on the physical environment and mobility.
    # Simple variant of Rayleigh fading with Doppler effect. In practice, this would be more complex and 
    # depend on the velocity of the transmitter/receiver and the carrier frequency.
    # This Doppler effect is actually called Fast Rayleigh Fading, while the velocity dependency can be a "Jakes Model" or similar. 
    
    fading_coefficients = doppler ? randn(N) + im * randn(N) : randn() + im * randn() # Single fading for flat fading, or a vector for frequency selective fading
    channel_gain = fading_coefficients ./ sqrt(mean(abs2, fading_coefficients)) # Normalise the fading

    signal_faded = signal .* channel_gain
    return signal_faded, channel_gain
end

# Additive White Gaussian Noise (AWGN) function
function apply_awgn(signal; SNR_dB=-5.0)
    signal_power = mean(abs2, signal)
    noise_power = signal_power / (10^(SNR_dB / 10))
    noise = sqrt(noise_power / 2) .* randn(length(signal)) .+ im .* sqrt(noise_power / 2) .* randn(length(signal))
    signal_final = signal .+ noise
    return signal_final
end

function apply_channel_effects(signal::Vector{<:Number}, snr_db::Float64; doppler::Bool=false)
    signal_faded, channel_gain = apply_rayleigh_fading(signal, doppler=doppler)
    signal_final = apply_awgn(signal_faded, SNR_dB=snr_db)
    return signal_final, channel_gain
end

# ==============================================================================
# 5. RECEIVER UTILITIES (For plotting and verification)
# ==============================================================================
function apply_carrier(baseband_signal::Vector{ComplexF64}, fc::Float64, fs::Float64)
    t = (0:length(baseband_signal)-1) ./ fs
    # Multiply by carrier and take the real part to get the physical passband signal
    carrier = exp.(im .* 2π .* fc .* t)
    passband_signal = real.(baseband_signal .* carrier)
    
    return passband_signal
end

function demodulate_signal(passband_signal::Vector{Float64}, sps::Int, fc::Float64, fs::Float64, h_rrc::Vector{Float64}; downsample::Bool=true)
    t = (0:length(passband_signal)-1) ./ fs

    # 1. Downconvert to baseband (Multiply by * 2.0 to recover amplitude lost in modulation)
    baseband_rx = passband_signal .* exp.(-im .* 2π .* fc .* t) .* 2.0

    # Trimming the tail to match length of original signal before convolution to avoid issues with the convolution and time vector lengths.
    # Find the delay created by the convolution with the RRC and trim the demodulated signals. 
    # 2. Matched Filter
    delay = floor(Int, length(h_rrc) / 2)
    conv_indices = delay + 1 : delay + length(baseband_rx)
    matched = conv(baseband_rx, h_rrc)[conv_indices]

    # Timing Recovery: Pick the correct sample (peak of the poulse) to decide the symbol
    # This is a simple timing offset. In practice, this would be determined by a timing recovery algorithm.
    # Thanks to the trimming, we can pick samples starting at idx 1 now.

    # # 3. Downsample to get the exact symbols back!
    # symbols_rx = matched[1:sps:end]

    # return real.(symbols_rx), imag.(symbols_rx)
    # return real.(matched), imag.(matched)

    # 3. Trim RRC boundary transients and optionally downsample to symbol peaks
    edge_syms = div(round(Int, (length(h_rrc) - 1) / sps), 2)
    if downsample
        indices = (1:sps:length(matched))[(1 + edge_syms) : (end - edge_syms)]
        symbols_rx = matched[indices]
        return real.(symbols_rx), imag.(symbols_rx)
    else
        trim_samples = edge_syms * sps
        matched_trimmed = matched[(1 + trim_samples) : (end - trim_samples)]
        return real.(matched_trimmed), imag.(matched_trimmed)
    end
end


# ==============================================================================
# 6. THE MASTER GENERATOR
# ==============================================================================
function generate_signal(emitter::TargetEmitter, num_symbols::Int)
    # ===============================
    # CLEAN QPSK SIGNAL FOR PLOTTING
    # ===============================
    syms = generate_qpsk_symbols(num_symbols)
    h_rrc = create_rrc_filter(emitter.sps, emitter.β, emitter.span)

    # Pulse shape the symbols
    shaped_baseband = apply_pulse_shaping(syms, h_rrc, emitter.sps)

    # Upconvert to Passband
    qpsk_passband = apply_carrier(shaped_baseband, emitter.fc, emitter.fs)

    # ==============
    # DSSS PIPELINE
    # ==============
    code_len = 2^emitter.lfsr_bits - 1
    code = generate_gold_code(code_len; seed=emitter.id)
    syms_spread = apply_dsss(syms, code)
    
    h_rrc_chip = create_rrc_filter(emitter.sps_chip, emitter.β, emitter.span)
    # Upconvert to Passband (for plotting. FHSS will be the one we use for the final channel effects)
    dsss_baseband = apply_pulse_shaping(syms_spread, h_rrc_chip, emitter.sps_chip) ./ sqrt(code_len)
    # Upconvert to Passband (for Figure 3 plotting; FHSS uses dsss_baseband below)
    dsss_passband = apply_carrier(dsss_baseband, emitter.fc, emitter.fs)
    # ========================
    # FHSS AND CHANNEL EFFECTS
    # ========================
    # Upconvert & Hopping
    fhss_passband = apply_frequency_hopping(dsss_baseband, emitter.fs, emitter.hop_rate, emitter.hop_freq)
    
    # Channel Effects
    final_rx, _ = apply_channel_effects(fhss_passband, emitter.snr_db; doppler=true)
    
    # Return everything neatly packaged!
    return (
        syms = syms,
        qpsk_clean = qpsk_passband, # The clean QPSK passband signal before spreading and hopping (float vector)
        dsss = dsss_passband,
        fhss = fhss_passband,
        final = final_rx,
        matched_filter = h_rrc,             # For QPSK demodulation
        matched_filter_chip = h_rrc_chip    # For DSSS demodulation
    )
end

