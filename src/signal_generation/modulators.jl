# ==============================================================================
# 2. MODULATION & SPREADING
# ==============================================================================
function generate_qpsk_symbols(num_symbols::Int)
    bits = rand(0:1, 2 * num_symbols) # Random bits
    # Reshape bits into a 2-row matrix to process pairs
    bit_pairs = reshape(bits, 2, :)

    # Map bit pairs to QPSK symbols
    # Map 0 -> -1 and 1 -> +1
    I_syms = 2 .* bit_pairs[1, :] .- 1.0
    Q_syms = 2 .* bit_pairs[2, :] .- 1.0
    # return I_syms, Q_syms
    # Combine them into a single complex array:
    complex_syms = I_syms .+ im .* Q_syms
    return complex_syms
end

# Function generating a Pseudo-random Noise (PN) code for DSSS. A simple implementation using Linear Feedback Shift Register (LFSR).
# Since we are hiding the signal for the receiver, we can use a simple PN code. 

# Gold code generator for DSSS spreading. This is a simple implementation and can be replaced with more complex codes if needed.
# ====== Gold code function has been generated by LLM ======
function generate_gold_code(n_bits::Int; seed::Int=1)
    # Standard 7-bit LFSR preferred pairs for a length-127 sequence
    # Polynomials: x^7 + x^3 + 1 and x^7 + x^3 + x^2 + x^1 + 1
    reg1 = ones(Int, 7)
    reg2 = digits(mod1(seed, 127), base=2, pad=7)
    
    code = zeros(Float64, n_bits)
    
    for i in 1:n_bits
        # XOR the outputs of the two registers
        code[i] = (reg1[end] != reg2[end]) ? 1.0 : -1.0
        
        # Shift Register 1 Feedback
        fb1 = xor(reg1[7], reg1[3])
        reg1 = vcat(fb1, reg1[1:6])
        
        # Shift Register 2 Feedback
        fb2 = xor(xor(xor(reg2[7], reg2[3]), reg2[2]), reg2[1])
        reg2 = vcat(fb2, reg2[1:6])
    end
    return code
end

# Apply DSSS spreading to QPSK symbols
function apply_dsss(complex_syms::Vector{ComplexF64}, PN_code::Vector{Float64})
    # Kronecker product to spread the complex symbols
    spread_signal = kron(complex_syms, PN_code)
    return spread_signal
end

